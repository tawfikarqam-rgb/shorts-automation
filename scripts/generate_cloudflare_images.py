#!/usr/bin/env python3
"""Generate a small, bounded set of story-scene images with Cloudflare Workers AI.

This script only generates images. Story text remains in the reviewed local library.
If Cloudflare is not configured or a request fails, the existing open-license image
download step remains responsible for supplying usable visuals.
"""
import base64
import os
import re
from pathlib import Path

import requests

MODEL = "@cf/black-forest-labs/flux-1-schnell"
OUTPUT_DIR = Path("MoneyPrinterTurbo/storage/local_videos")
MAX_IMAGES = 3
STEPS = 4
TIMEOUT = (20, 180)


def build_prompt(scene_description):
    scene = re.sub(r"\s+", " ", str(scene_description or "")).strip()
    if not scene:
        raise ValueError("Scene description must not be empty")
    return (
        f"Cinematic documentary-style image illustrating: {scene}. "
        "Photorealistic editorial reconstruction, visually clear main subject, "
        "natural cinematic lighting, historically appropriate clothing, objects "
        "and architecture where relevant, realistic textures, strong composition "
        "for a vertical short-form video. No text, no letters, no captions, "
        "no logos, no watermark, no borders, no collage."
    )


def extract_image_bytes(response):
    content_type = response.headers.get("Content-Type", "").lower()
    if content_type.startswith("image/"):
        image_bytes = response.content
    else:
        payload = response.json()
        result = payload.get("result") or {}
        image_value = result.get("image") or payload.get("image")
        if not isinstance(image_value, str) or not image_value:
            raise ValueError("Cloudflare response did not contain an image")
        image_bytes = base64.b64decode(image_value, validate=True)

    if image_bytes.startswith(b"\x89PNG\r\n\x1a\n"):
        extension = ".png"
    elif image_bytes.startswith(b"RIFF") and image_bytes[8:12] == b"WEBP":
        extension = ".webp"
    else:
        extension = ".jpg"
    return image_bytes, extension


def main():
    account_id = os.environ.get("CLOUDFLARE_ACCOUNT_ID", "").strip()
    api_token = os.environ.get("CLOUDFLARE_API_TOKEN", "").strip()
    if not account_id or not api_token:
        print("CLOUDFLARE_IMAGE_STATUS=SKIPPED (credentials not configured)")
        return 0

    searches = [item.strip() for item in os.environ.get("IMAGE_SEARCHES", "").split(";") if item.strip()]
    if not searches:
        print("CLOUDFLARE_IMAGE_STATUS=SKIPPED (no scene descriptions)")
        return 0

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for stale in OUTPUT_DIR.glob("cloudflare_scene_*"):
        stale.unlink(missing_ok=True)

    endpoint = (
        "https://api.cloudflare.com/client/v4/accounts/"
        + account_id
        + "/ai/run/"
        + MODEL
    )
    headers = {
        "Authorization": "Bearer " + api_token,
        "Content-Type": "application/json",
    }
    generated = 0
    for index, scene in enumerate(searches[:MAX_IMAGES], start=1):
        try:
            response = requests.post(
                endpoint,
                headers=headers,
                json={"prompt": build_prompt(scene), "steps": STEPS},
                timeout=TIMEOUT,
            )
            response.raise_for_status()
            image_bytes, extension = extract_image_bytes(response)
            if len(image_bytes) < 10000:
                raise ValueError("Generated image response is unexpectedly small")

            output_path = OUTPUT_DIR / f"cloudflare_scene_{index}{extension}"
            output_path.write_bytes(image_bytes)
            generated += 1
            print(f"CLOUDFLARE_IMAGE_{index}=GENERATED bytes={len(image_bytes)}")
        except Exception as exc:
            # Do not print request headers or secrets. The free image-search
            # providers remain available as fallback.
            print(f"CLOUDFLARE_IMAGE_{index}=FAILED error={type(exc).__name__}: {exc}")

    print(f"CLOUDFLARE_IMAGE_STATUS=COMPLETE generated={generated} limit={MAX_IMAGES}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
